  const AppLocalizations(this.locale);

  final Locale locale;

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) {
    final result = Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(result != null, 'AppLocalizations was not found in the widget tree.');
    return result!;
  }

  String get _code {
    if (locale.languageCode.toLowerCase().startsWith('en')) return 'en';
    if (locale.languageCode.toLowerCase().startsWith('zh')) return 'zh';
    return 'vi';
  }

  String tr(String source, [Map<String, Object?> params = const {}]) {
    var value = _translations[_code]?[source];

    if (value == null && source.startsWith('Không thể kết nối máy chủ: ')) {
      value = _translations[_code]?['Không thể kết nối máy chủ: {error}'];
      params = <String, Object?>{
        ...params,
        'error': source.substring('Không thể kết nối máy chủ: '.length),
      };
    }

    var resolvedValue = value ?? source;
    for (final entry in params.entries) {
      resolvedValue = resolvedValue.replaceAll(
        '{${entry.key}}',
        '${entry.value ?? ''}',
      );
    }
    return resolvedValue;
  }

  String languageName(AppLanguage language) {
    switch (_code) {
      case 'en':
        return language.englishName;
      case 'zh':
        switch (language) {
          case AppLanguage.vietnamese:
            return '越南语';
          case AppLanguage.english:
            return '英语';
          case AppLanguage.chinese:
            return '中文';
        }
      default:
        switch (language) {
          case AppLanguage.vietnamese:
            return 'Tiếng Việt';
          case AppLanguage.english:
            return 'Tiếng Anh';
          case AppLanguage.chinese:
            return 'Tiếng Trung';
        }
    }
  }

