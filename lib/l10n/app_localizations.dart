  static AppLocalizations of(BuildContext context) {
    final result = Localizations.of<AppLocalizations>(context, AppLocalizations);
    assert(result != null, 'AppLocalizations was not found in the widget tree.');
    return result!;
  }

  String get _code {
    if (locale.languageCode.toLowerCase().startsWith('en')) return 'en';
    if (locale.languageCode.toLowerCase().startsWith('zh')) return 'zh';
    return 'vi';
  }

  String tr(String source, [Map<String, Object?> params = const {}]) {
    var value = _translations[_code]?[source];

    if (value == null && source.startsWith('Không thể kết nối máy chủ: ')) {
      value = _translations[_code]?['Không thể kết nối máy chủ: {error}'];
      params = <String, Object?>{
        ...params,
        'error': source.substring('Không thể kết nối máy chủ: '.length),
      };
    }

    if (value == null &&
        source.startsWith(
          'Kết nối tới máy chủ bị ngắt khi đang nhận dữ liệu: ',
        )) {
      const prefix = 'Kết nối tới máy chủ bị ngắt khi đang nhận dữ liệu: ';
      value = _translations[_code]?[
          'Kết nối tới máy chủ bị ngắt khi đang nhận dữ liệu: {error}'];
      params = <String, Object?>{
        ...params,
        'error': source.substring(prefix.length),
      };
    }

    if (value == null && source.startsWith('Môi giới Lv')) {
      final level = source.substring('Môi giới Lv'.length).trim();
      if (level.isNotEmpty && int.tryParse(level) != null) {
        value = _translations[_code]?['Môi giới Lv{level}'];
        params = <String, Object?>{
          ...params,
          'level': level,
        };
      }
    }

    // Một số API/model cũ trả chuỗi giá đã định dạng bằng tiếng Việt
    // (ví dụ: "35 triệu/tháng", "8,2 tỷ", "299.000 đ/tháng").
    // Chuẩn hóa các hậu tố này tại lớp i18n để giao diện EN/ZH không bị
    // lẫn tiếng Việt, đồng thời vẫn giữ nguyên phần số mà backend trả về.
    if (value == null && _code != 'vi') {
      void resolveDynamicAmount(RegExp pattern, String translationKey) {
        if (value != null) return;
        final match = pattern.firstMatch(source.trim());
        final amount = match?.group(1)?.trim() ?? '';
        if (amount.isEmpty) return;
        value = _translations[_code]?[translationKey];
        params = <String, Object?>{
          ...params,
          'amount': amount,
        };
      }

      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*triệu\s*/\s*tháng$', caseSensitive: false),
        '{amount} triệu/tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*tỷ\s*/\s*tháng$', caseSensitive: false),
        '{amount} tỷ/tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*nghìn\s*/\s*tháng$', caseSensitive: false),
        '{amount} nghìn/tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*đ\s*/\s*tháng$', caseSensitive: false),
        '{amount} đ/tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*triệu$', caseSensitive: false),
        '{amount} triệu',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*tỷ$', caseSensitive: false),
        '{amount} tỷ',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*nghìn$', caseSensitive: false),
        '{amount} nghìn',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s*đ$', caseSensitive: false),
        '{amount} đ',
      );
      resolveDynamicAmount(
        RegExp(r'^Tối\s+thiểu\s+(.+?)\s+tháng$', caseSensitive: false),
        'Tối thiểu {amount} tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+phòng\s+ngủ$', caseSensitive: false),
        '{amount} phòng ngủ',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+phòng\s+tắm$', caseSensitive: false),
        '{amount} phòng tắm',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+phòng\s+khách$', caseSensitive: false),
        '{amount} phòng khách',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+phòng\s+thờ$', caseSensitive: false),
        '{amount} phòng thờ',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+tầng$', caseSensitive: false),
        '{amount} tầng',
      );
      resolveDynamicAmount(
        RegExp(r'^Tầng\s+(.+)$', caseSensitive: false),
        'Tầng {amount}',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+tháng$', caseSensitive: false),
        '{amount} tháng',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+năm$', caseSensitive: false),
        '{amount} năm',
      );
      resolveDynamicAmount(
        RegExp(r'^Mặt\s+tiền\s+(.+)$', caseSensitive: false),
        'Mặt tiền {amount}',
      );
      resolveDynamicAmount(
        RegExp(r'^Đường\s+(.+)$', caseSensitive: false),
        'Đường {amount}',
      );
      resolveDynamicAmount(
        RegExp(r'^(.+?)\s+tấn\s*/\s*m²$', caseSensitive: false),
        '{amount} tấn/m²',
      );
    }

    var resolvedValue = value ?? source;
    for (final entry in params.entries) {
      resolvedValue = resolvedValue.replaceAll(
        '{${entry.key}}',
        '${entry.value ?? ''}',
      );
    }
    return resolvedValue;
  }

  String languageName(AppLanguage language) {
    switch (_code) {
      case 'en':
        return language.englishName;
      case 'zh':
        switch (language) {
          case AppLanguage.vietnamese:
            return '越南语';
          case AppLanguage.english:
            return '英语';
          case AppLanguage.chinese:
            return '中文';
        }
      default:
        switch (language) {
          case AppLanguage.vietnamese:
            return 'Tiếng Việt';
          case AppLanguage.english:
            return 'Tiếng Anh';
          case AppLanguage.chinese:
            return 'Tiếng Trung';
        }
    }
  }

